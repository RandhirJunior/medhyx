// Extracts visible text from the site's HTML pages into src/knowledge.js,
// so the assistant answers from what medhyx.com actually says.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const siteRoot = path.resolve(here, '../..');
const outFile = path.resolve(here, '../src/knowledge.js');

const PAGES = [
  { file: 'index.html', url: 'https://medhyx.com/' },
  { file: 'solutions.html', url: 'https://medhyx.com/solutions' },
  { file: 'architecture.html', url: 'https://medhyx.com/architecture' },
  { file: 'technologies.html', url: 'https://medhyx.com/technologies' },
  { file: 'case-studies.html', url: 'https://medhyx.com/case-studies' },
  { file: 'careers.html', url: 'https://medhyx.com/careers' },
  { file: 'contact.html', url: 'https://medhyx.com/contact' },
];

const ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', bull: '•', rarr: '→', larr: '←', uarr: '↑', darr: '↓', nearr: '↗', mdash: '—', ndash: '–', copy: '©', times: '×', middot: '·', hellip: '…', ldquo: '“', rdquo: '”', lsquo: '‘', rsquo: '’', check: '✓' };

function decodeEntities(s) {
  return s
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&([a-z]+);/gi, (m, n) => ENTITIES[n.toLowerCase()] ?? m);
}

function htmlToText(html) {
  return decodeEntities(
    html
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/<(script|style|svg|noscript|template)\b[\s\S]*?<\/\1>/gi, '')
      .replace(/<(input|textarea|select)\b[^>]*>/gi, '')
      .replace(/<h([1-6])\b[^>]*>/gi, (_, n) => `\n\n${'#'.repeat(Math.min(Number(n) + 1, 6))} `)
      .replace(/<\/h[1-6]>/gi, '\n')
      .replace(/<li\b[^>]*>/gi, '\n- ')
      .replace(/<(br|hr)\b[^>]*>/gi, '\n')
      .replace(/<\/(p|div|section|article|li|ul|ol|tr|table|blockquote|figure|label|option|summary|details|dd|dt)>/gi, '\n')
      .replace(/<(td|th)\b[^>]*>/gi, ' | ')
      .replace(/<[^>]+>/g, ' ')
  )
    .split('\n')
    .map(line => line.replace(/[ \t ]+/g, ' ').trim())
    .filter(line => line && line !== '-' && line !== '|')
    .join('\n')
    .replace(/\n{3,}/g, '\n\n');
}

function extract(html, tag) {
  const m = html.match(new RegExp(`<${tag}\\b[^>]*>([\\s\\S]*?)</${tag}>`, 'i'));
  if (!m) throw new Error(`<${tag}> not found`);
  return m[1];
}

const sections = PAGES.map(({ file, url }) => {
  const html = readFileSync(path.join(siteRoot, file), 'utf8');
  const title = decodeEntities(extract(html, 'title')).trim();
  const description = html.match(/<meta\s+name="description"\s+content="([^"]*)"/i)?.[1];
  const body = htmlToText(extract(html, 'main'));
  return `<page url="${url}" title="${title}">\n${description ? `Summary: ${decodeEntities(description)}\n\n` : ''}${body}\n</page>`;
});

const indexHtml = readFileSync(path.join(siteRoot, 'index.html'), 'utf8');
const footer = htmlToText(extract(indexHtml, 'footer'));
sections.push(`<page url="https://medhyx.com/" title="Site footer (company details)">\n${footer}\n</page>`);

const knowledge = sections.join('\n\n');
writeFileSync(outFile, `// Generated by scripts/build-knowledge.mjs — do not edit by hand.\nexport const SITE_KNOWLEDGE = ${JSON.stringify(knowledge)};\n`);
console.log(`Wrote ${path.relative(process.cwd(), outFile)}: ${knowledge.length} chars (~${Math.round(knowledge.length / 4)} tokens) from ${PAGES.length} pages`);
